#!/usr/bin/env python3
"""decomp2c_regen.py — regenerate a committed decomp2c module with today's converter, keeping its hand finishes.

    python3 tools/ida/decomp2c_regen.py src/x.c [--keep 0xVA,0xVA] [--flags "--typed --zero-locals"] [--dry]

The module's functions (its `/* 0xVA: <IDA head> */` blocks, in order) are regenerated in ONE decomp2c run (so
cross-calls bind the same way); the module header (everything before the converter's first `#include` / `#pragma`)
is kept; a function listed in --keep keeps its committed body (a hand finish) and is reported if the fresh body
differs.  Modules with a finish script (tools/ida/finish/<module>.py) are regenerated by that script instead.
Prints, per function, whether it changed.  --dry writes nothing.  Run inside nix develop."""
import argparse
import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(REPO, "tools", "ida"))
from decomp2c_drift import funcs_of, norm   # noqa: E402


def body_start(text):
    return min(i for i in (text.find("#include <windows.h>"), text.find("#pragma GCC")) if i >= 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("module")
    ap.add_argument("--keep", default="", help="VAs whose committed body is a hand finish (kept)")
    ap.add_argument("--flags", default="--typed --zero-locals")
    ap.add_argument("--dry", action="store_true")
    ap.add_argument("--show", action="store_true", help="print each regenerated function's changed lines")
    a = ap.parse_args()
    path = os.path.join(REPO, a.module)
    name = os.path.splitext(os.path.basename(path))[0]
    fin = os.path.join(REPO, "tools", "ida", "finish", name + ".py")
    if os.path.exists(fin):
        sys.exit(f"{a.module}: has a finish script — run python3 {os.path.relpath(fin, REPO)}")
    text = open(path).read()
    fs = funcs_of(text)
    keep = {k.lower().replace("0x", "") for k in a.keep.split(",") if k}
    cmd = [sys.executable, os.path.join(REPO, "tools", "ida", "decomp2c.py")] + a.flags.split() + [f"{va}:{n}" for va, n, _ in fs]
    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO)
    if r.returncode:
        sys.exit(r.stderr[-2000:])
    out = r.stdout
    new = out[min(i for i in (out.find("#include"), out.find("#pragma")) if i >= 0):]
    old = {va: b for va, _, b in fs}
    changed = []
    for va, n, b in funcs_of(new):
        if norm(b) == norm(old.get(va, "")):
            continue
        if va in keep:
            print(f"0x{va} {n}: KEPT (hand finish; the fresh body differs)")
            new = new.replace(b, old[va], 1)
        else:
            changed.append(f"0x{va}")
            if a.show:
                import difflib
                d = [l for l in difflib.unified_diff(norm(old.get(va, "")), norm(b), lineterm="", n=0) if l[:1] in "+-" and l[:3] not in ("+++", "---")]
                print(f"--- 0x{va} {n}"); print("\n".join("    " + l[:220] for l in d[:40]))
    print(f"{a.module}: {len(fs)} functions, {len(changed)} regenerated" + (": " + " ".join(changed) if changed else ""))
    if not a.dry:
        open(path, "w").write(text[:body_start(text)] + new)


if __name__ == "__main__":
    main()
